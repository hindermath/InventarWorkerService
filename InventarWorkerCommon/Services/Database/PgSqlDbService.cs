    /// <summary>
    /// DE: Importiert Maschinen aus einer CSV-Datei innerhalb einer PostgreSQL-Transaktion.
    /// Vorhandene Maschinen werden uebersprungen; bei Fehlern wird vollstaendig zurueckgerollt.
    /// EN: Imports machines from a CSV file inside a PostgreSQL transaction.
    /// Existing machines are skipped; failures trigger a full rollback.
    /// </summary>
    /// <param name="csvFilePath">DE: Pfad zur CSV-Datei. EN: Path to the CSV file.</param>
    /// <returns>
    /// DE: Anzahl neu importierter Maschinen.
    /// EN: Number of newly imported machines.
    /// </returns>
    /// <exception cref="FileNotFoundException">
    /// DE: Wird geworfen, wenn die CSV-Datei nicht existiert.
    /// EN: Thrown when the CSV file does not exist.
    /// </exception>
    /// <exception cref="Exception">
    /// DE: Wird geworfen, wenn der Import fehlschlaegt und ein Rollback ausgeloest wurde.
    /// EN: Thrown when the import fails and a rollback was triggered.
    /// </exception>
    public async Task<int> InitializeMachinesFromCsvAsync(string csvFilePath)
    {
        if (File.Exists(csvFilePath) is false)
        {
            throw new FileNotFoundException($"The specified CSV file does not exist {csvFilePath}.");
        }

        var importedCount = 0;
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync().ConfigureAwait(false);

        await using var transaction = await connection.BeginTransactionAsync().ConfigureAwait(false);

        try
        {
            using var reader = new StreamReader(csvFilePath);
            using var csv = new CsvReader(reader, CultureInfo.InvariantCulture);

            csv.Context.RegisterClassMap<MachineMapFromCsv>();

            var machines = csv.GetRecords<MachineFromCsv>().ToList();

            foreach (var machine in machines)
            {
                if (string.IsNullOrWhiteSpace(machine.Name))
                {
                    throw new InvalidOperationException("Machine name must not be empty during CSV import.");
                }

                const string selectQuery = "SELECT Id FROM Machines WHERE Name = @Name";
                var existingMachineId = await connection.QuerySingleOrDefaultAsync<int?>(
                    selectQuery,
                    new { machine.Name },
                    transaction).ConfigureAwait(false);

                if (existingMachineId.HasValue)
                {
                    continue;
                }

                const string insertQuery =
                    """
                    INSERT INTO Machines (Name, OperatingSystem, LastSeen, CreatedAt, IPv4, IPv6, FQDN, Disabled, Deprovisioned)
                    VALUES (@Name, @OperatingSystem, @LastSeen, @CreatedAt, @IPv4, @IPv6, @FQDN, @Disabled, @Deprovisioned)
                    """;

                await connection.ExecuteAsync(
                    insertQuery,
                    new
                    {
                        machine.Name,
                        machine.OperatingSystem,
                        LastSeen = machine.LastSeen ?? DateTime.UtcNow,
                        CreatedAt = DateTime.UtcNow,
                        machine.IPv4,
                        machine.IPv6,
                        machine.FQDN,
                        machine.Disabled,
                        machine.Deprovisioned
                    },
                    transaction).ConfigureAwait(false);

                importedCount++;
            }

            await transaction.CommitAsync().ConfigureAwait(false);
            return importedCount;
        }
        catch (Exception ex)
        {
            await transaction.RollbackAsync().ConfigureAwait(false);
            throw new Exception("Import fehlgeschlagen — Transaktion zurückgerollt.", ex);
        }
    }

    private void EnsureDatabaseExists(string targetDatabase)
    {
        var adminCsBuilder = new NpgsqlConnectionStringBuilder(_connectionString)
        {
            Database = "postgres"
        };

        using var adminConnection = new NpgsqlConnection(adminCsBuilder.ConnectionString);
        adminConnection.Open();

        using var checkDbExistsCmd = new NpgsqlCommand("SELECT 1 FROM pg_database WHERE datname = @dbname", adminConnection);
        checkDbExistsCmd.Parameters.AddWithValue("dbname", targetDatabase);
        var dbExists = checkDbExistsCmd.ExecuteScalar() is not null;

        if (dbExists is false)
        {
            var quotedDbName = QuoteIdentifier(targetDatabase);
            using var createCmd = new NpgsqlCommand($"CREATE DATABASE {quotedDbName}", adminConnection);
            createCmd.ExecuteNonQuery();
        }
    }

    private string GetTargetDatabaseName()
    {
        var csStringBuilder = new NpgsqlConnectionStringBuilder(_connectionString);
        var dbName = csStringBuilder.Database;

        if (string.IsNullOrWhiteSpace(dbName))
        {
            throw new InvalidOperationException("No target database specified in the PostgreSQL connection string.");
        }

        return dbName;
    }

    private static string QuoteIdentifier(string identifier)
    {
        return "\"" + identifier.Replace("\"", "\"\"") + "\"";
    }
