    /// <summary>
    /// DE: Berechnet den UTC-Cutoff fuer Aufraeumoperationen.
    /// EN: Calculates the UTC cutoff for cleanup operations.
    /// </summary>
    /// <param name="daysToKeep">DE: Anzahl Tage, die behalten werden sollen. EN: Number of days to keep.</param>
    /// <returns>
    /// DE: UTC-Zeitpunkt fuer die Loeschgrenze.
    /// EN: UTC timestamp used as the delete threshold.
    /// </returns>
    internal static DateTime CalculateCutoff(int daysToKeep) => DateTime.UtcNow.AddDays(-daysToKeep);

    /// <summary>
    /// DE: Loescht Hardware- und Software-Eintraege, die aelter als der berechnete Cutoff sind.
    /// EN: Deletes hardware and software rows that are older than the calculated cutoff.
    /// </summary>
    /// <param name="daysToKeep">DE: Aufbewahrungsdauer in Tagen. EN: Retention period in days.</param>
    public async Task CleanupOldRecordsAsync(int daysToKeep = 30)
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync().ConfigureAwait(false);

        var cutoffDate = CalculateCutoff(daysToKeep);

        const string deleteHardwareQuery = "DELETE FROM HardwareInventories WHERE CreatedAt < @CutoffDate";
        const string deleteSoftwareQuery = "DELETE FROM SoftwareInventories WHERE CreatedAt < @CutoffDate";

        await connection.ExecuteAsync(deleteHardwareQuery, new { CutoffDate = cutoffDate }).ConfigureAwait(false);
        await connection.ExecuteAsync(deleteSoftwareQuery, new { CutoffDate = cutoffDate }).ConfigureAwait(false);
    }

