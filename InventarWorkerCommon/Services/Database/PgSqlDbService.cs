    /// <summary>
    /// DE: Erstellt die benoetigten Tabellen, Indizes und Views fuer PostgreSQL.
    /// EN: Creates the required PostgreSQL tables, indexes, and views.
    /// </summary>
    public void InitializeDatabase()
    {
#if DEBUG
        var targetDatabase = GetTargetDatabaseName();
        EnsureDatabaseExists(targetDatabase);
#else
        EnsureDatabaseExists(GetTargetDatabaseName());
#endif

        using var connection = new NpgsqlConnection(_connectionString);
        connection.Open();

        var createTablesAndViewsQuery =
            """
            CREATE TABLE IF NOT EXISTS Machines (
                Id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                Name TEXT NOT NULL UNIQUE,
                OperatingSystem TEXT,
                LastSeen timestamptz,
                CreatedAt timestamptz DEFAULT now(),
                IPv4 TEXT,
                IPv6 TEXT,
                FQDN TEXT,
                Disabled BOOLEAN NOT NULL DEFAULT FALSE,
                Deprovisioned BOOLEAN NOT NULL DEFAULT FALSE,
                LastHarvested timestamptz
            );

            CREATE TABLE IF NOT EXISTS HardwareInventories (
               Id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
               MachineId INTEGER NOT NULL,
               ComputerName TEXT,
               ComputerModel TEXT,
               ComputerManufacturer TEXT,
               Architecture TEXT,
               ProcessorName TEXT,
               ProcessorCores INTEGER,
               TotalMemoryGB REAL,
               AvailableMemoryGB REAL,
               MemoryUsagePercent REAL,
               CreatedAt timestamptz DEFAULT now(),
               FOREIGN KEY (MachineId) REFERENCES Machines(Id)
            );

            CREATE TABLE IF NOT EXISTS SoftwareInventories (
               Id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
               MachineId INTEGER NOT NULL,
               ProcessesJson TEXT,
               InstalledSoftwareJson TEXT,
               ServicesJson TEXT,
               EnvironmentJson TEXT,
               StartupProgramsJson TEXT,
               RuntimeJson TEXT,
               CreatedAt timestamptz DEFAULT now(),
               FOREIGN KEY (MachineId) REFERENCES Machines(Id)
            );

            CREATE INDEX IF NOT EXISTS idx_machines_name ON Machines(Name);
            CREATE INDEX IF NOT EXISTS idx_hardware_machine_created ON HardwareInventories(MachineId, CreatedAt);
            CREATE INDEX IF NOT EXISTS idx_software_machine_created ON SoftwareInventories(MachineId, CreatedAt);

            DROP VIEW IF EXISTS hardware_inventory_view;

            CREATE OR REPLACE VIEW HardwareInventoryView AS
            SELECT DISTINCT ON (m.id)
                m.id AS MachineID,
                m.name AS MachineName,
                h.Architecture,
                h.ProcessorCores,
                ROUND(h.TotalMemoryGB::numeric / 1024 / 1024 / 1024, 2) AS TotalMemoryGB,
                ROUND(h.AvailableMemoryGB::numeric / 1024 / 1024 / 1024, 2) AS AvailableMemoryGB,
                ROUND(h.MemoryUsagePercent::numeric, 2) AS MemoryUsagePercent
            FROM Machines m
                JOIN HardwareInventories h ON h.MachineId = m.Id
            ORDER BY m.Id, h.CreatedAt DESC;

            CREATE OR REPLACE VIEW LatestSoftwareInventoriesView AS
            SELECT si.*
            FROM SoftwareInventories si
                INNER JOIN (
                    SELECT MachineId, MAX(CreatedAt) AS MaxCreatedAt
                    FROM SoftwareInventories
                    GROUP BY MachineId
                ) latest ON si.MachineId = latest.MachineId AND si.CreatedAt = latest.MaxCreatedAt
            ORDER BY si.CreatedAt DESC;

            CREATE OR REPLACE VIEW LatestHardwareInventoriesView AS
            SELECT * FROM (
                SELECT *,
                       ROW_NUMBER() OVER (PARTITION BY MachineId ORDER BY CreatedAt DESC) AS rn
                FROM HardwareInventories
            ) ranked
            WHERE rn = 1
            ORDER BY CreatedAt DESC;

            CREATE OR REPLACE VIEW ComputerModelStatisticsView AS
            SELECT
                ComputerModel,
                COUNT(*) AS AnzahlMaschinen,
                COUNT(DISTINCT MachineId) AS EinzigartigeMaschinen,
                ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM LatestHardwareInventoriesView), 2) AS Prozentsatz,
                MIN(CreatedAt) AS ErsteErfassung,
                MAX(CreatedAt) AS LetzteErfassung
            FROM LatestHardwareInventoriesView
            WHERE ComputerModel IS NOT NULL
              AND ComputerModel != ''
            GROUP BY ComputerModel
            ORDER BY AnzahlMaschinen DESC;

            CREATE OR REPLACE VIEW ArchitectureStatisticsView AS
            SELECT
                Architecture,
                COUNT(*) AS AnzahlMaschinen,
                COUNT(DISTINCT MachineId) AS EinzigartigeMaschinen,
                ROUND(COUNT(*)::numeric * 100.0 / (SELECT COUNT(*) FROM LatestHardwareInventoriesView)::numeric, 2) AS Prozentsatz,
                AVG(ProcessorCores) AS DurchschnittlicheKerne,
                ROUND(AVG(TotalMemoryGB::numeric / 1024 / 1024 / 1024), 2) AS DurchschnittlicherSpeicherGB,
                MIN(CreatedAt) AS ErsteErfassung,
                MAX(CreatedAt) AS LetzteErfassung
            FROM LatestHardwareInventoriesView
            WHERE Architecture IS NOT NULL
              AND Architecture != ''
            GROUP BY Architecture
            ORDER BY AnzahlMaschinen DESC;

            CREATE OR REPLACE VIEW ModelArchitectureStatisticsView AS
            SELECT
                ComputerModel,
                Architecture,
                COUNT(*) AS AnzahlMaschinen,
                COUNT(DISTINCT MachineId) AS EinzigartigeMaschinen,
                ROUND(COUNT(*)::numeric * 100.0 / (SELECT COUNT(*) FROM LatestHardwareInventoriesView)::numeric, 2) AS Prozentsatz,
                ROUND(AVG(ProcessorCores::numeric), 0) AS DurchschnittlicheKerne,
                ROUND(AVG(TotalMemoryGB::numeric / 1024 / 1024 / 1024), 2) AS DurchschnittlicherSpeicherGB,
                MIN(CreatedAt) AS ErsteErfassung,
                MAX(CreatedAt) AS LetzteErfassung
            FROM LatestHardwareInventoriesView
            WHERE ComputerModel IS NOT NULL
              AND ComputerModel != ''
              AND Architecture IS NOT NULL
              AND Architecture != ''
            GROUP BY ComputerModel, Architecture
            ORDER BY AnzahlMaschinen DESC;

            CREATE OR REPLACE VIEW HardwareStatisticsOverview AS
            SELECT
                'ComputerModel' AS Kategorie,
                ComputerModel AS Wert,
                COUNT(*) AS Anzahl,
                ROUND(COUNT(*)::numeric * 100.0 / (SELECT COUNT(*) FROM LatestHardwareInventoriesView)::numeric, 2) AS Prozentsatz
            FROM LatestHardwareInventoriesView
            WHERE ComputerModel IS NOT NULL AND ComputerModel != ''
            GROUP BY ComputerModel

            UNION ALL

            SELECT
                'Architecture' AS Kategorie,
                Architecture AS Wert,
                COUNT(*) AS Anzahl,
                ROUND(COUNT(*)::numeric * 100.0 / (SELECT COUNT(*) FROM LatestHardwareInventoriesView)::numeric, 2) AS Prozentsatz
            FROM LatestHardwareInventoriesView
            WHERE Architecture IS NOT NULL AND Architecture != ''
            GROUP BY Architecture

            ORDER BY Kategorie, Anzahl DESC;

            CREATE OR REPLACE VIEW AllActiveMachinesView AS
            SELECT Id, Name, IPv4, IPv6, FQDN, Disabled, Deprovisioned, LastSeen, LastHarvested
            FROM Machines
            WHERE Disabled = FALSE AND Deprovisioned = FALSE;

            CREATE OR REPLACE VIEW AllActiveMachinesWithNetworkInfoView AS
            SELECT Id, Name, IPv4, IPv6, FQDN, Disabled, Deprovisioned, LastSeen, LastHarvested
            FROM Machines
            WHERE Disabled = FALSE AND Deprovisioned = FALSE AND (
                (IPv4 IS NOT NULL AND IPv4 != '') OR
                (IPv6 IS NOT NULL AND IPv6 != '') OR
                (FQDN IS NOT NULL AND FQDN != '')
            );

            CREATE OR REPLACE VIEW AllDisabledMachinesView AS
            SELECT Id, Name, IPv4, IPv6, FQDN, Disabled, Deprovisioned, LastSeen, LastHarvested
            FROM Machines
            WHERE Disabled = TRUE AND Deprovisioned = FALSE;

            CREATE OR REPLACE VIEW AllDeprovisionedMachinesView AS
            SELECT Id, Name, IPv4, IPv6, FQDN, Disabled, Deprovisioned, LastSeen, LastHarvested
            FROM Machines
            WHERE Disabled = TRUE AND Deprovisioned = TRUE;
            """;

        connection.Execute(createTablesAndViewsQuery);
    }

    /// <summary>
    /// DE: Speichert eine neue Maschine oder aktualisiert einen bestehenden Datensatz anhand des Namens.
    /// SQLite bleibt die fuehrende Datenbank; die explizite Id wird nach PostgreSQL uebernommen.
    /// EN: Saves a new machine or updates an existing row by name.
    /// SQLite remains the leading database; the explicit Id is adopted by PostgreSQL.
    /// </summary>
    /// <param name="machine">DE: Maschinenobjekt mit SQLite-Id. EN: Machine object with the SQLite Id.</param>
    /// <param name="isHarvester">DE: Steuert das erweiterte Harvester-Update. EN: Controls the extended harvester update.</param>
    /// <returns>
    /// DE: Die Id der gespeicherten Maschine.
    /// EN: The Id of the saved machine.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    /// DE: Wird geworfen, wenn <paramref name="machine"/> <c>null</c> ist.
    /// EN: Thrown when <paramref name="machine"/> is <c>null</c>.
    /// </exception>
    /// <exception cref="ArgumentException">
    /// DE: Wird geworfen, wenn <paramref name="machine"/> keine gueltige Id enthaelt.
    /// EN: Thrown when <paramref name="machine"/> does not contain a valid Id.
    /// </exception>
    public async Task<int> SaveOrUpdateMachineAsync(Machine machine, bool isHarvester = false)
    {
        ArgumentNullException.ThrowIfNull(machine);

        if (machine.Id == 0)
        {
            throw new ArgumentException("Machine Id must be provided from SQLite before saving to PostgreSQL.", nameof(machine));
        }

        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync().ConfigureAwait(false);

        const string selectQuery = "SELECT Id FROM Machines WHERE Name = @Name";
        var existingMachineId = await connection.QuerySingleOrDefaultAsync<int?>(selectQuery, new { machine.Name }).ConfigureAwait(false);
        var now = DateTime.UtcNow;

        if (existingMachineId.HasValue)
        {
            if (isHarvester)
            {
                const string updateHarvesterQuery =
                    """
                    UPDATE Machines
                    SET OperatingSystem = @OperatingSystem,
                        LastSeen = @LastSeen,
                        IPv4 = @IPv4,
                        IPv6 = @IPv6,
                        FQDN = @FQDN,
                        LastHarvested = @LastHarvested
                    WHERE Id = @Id
                    """;

                await connection.ExecuteAsync(
                    updateHarvesterQuery,
                    new
                    {
                        machine.OperatingSystem,
                        LastSeen = now,
                        machine.IPv4,
                        machine.IPv6,
                        machine.FQDN,
                        LastHarvested = now,
                        Id = existingMachineId.Value
                    }).ConfigureAwait(false);
            }
            else
            {
                const string updateQuery =
                    """
                    UPDATE Machines
                    SET OperatingSystem = @OperatingSystem,
                        LastSeen = @LastSeen
                    WHERE Id = @Id
                    """;

                await connection.ExecuteAsync(
                    updateQuery,
                    new
                    {
                        machine.OperatingSystem,
                        LastSeen = now,
                        Id = existingMachineId.Value
                    }).ConfigureAwait(false);
            }

            return existingMachineId.Value;
        }

        const string insertQuery =
            """
            INSERT INTO Machines (Id, Name, OperatingSystem, LastSeen, CreatedAt, IPv4, IPv6, FQDN, LastHarvested, Disabled, Deprovisioned)
            VALUES (@Id, @Name, @OperatingSystem, @LastSeen, @CreatedAt, @IPv4, @IPv6, @FQDN, @LastHarvested, @Disabled, @Deprovisioned)
            RETURNING Id
            """;

        return await connection.QuerySingleAsync<int>(
            insertQuery,
            new
            {
                machine.Id,
                machine.Name,
                machine.OperatingSystem,
                LastSeen = now,
                CreatedAt = now,
                machine.IPv4,
                machine.IPv6,
                machine.FQDN,
                LastHarvested = isHarvester ? now : (DateTime?)null,
                machine.Disabled,
                machine.Deprovisioned
            }).ConfigureAwait(false);
    }

    /// <summary>
    /// DE: Speichert eine Hardware-Momentaufnahme fuer die angegebene Maschine.
    /// EN: Saves a hardware snapshot for the specified machine.
    /// </summary>
    /// <param name="machineId">DE: Maschinen-Id. EN: Machine Id.</param>
    /// <param name="hardware">DE: Hardware-Inventar. EN: Hardware inventory.</param>
    public async Task SaveHardwareInventoryAsync(int machineId, HardwareInventory hardware)
    {
        await using var connection = new NpgsqlConnection(_connectionString);
        await connection.OpenAsync().ConfigureAwait(false);

        const string insertQuery =
            """
            INSERT INTO HardwareInventories
            (MachineId, ComputerName, ComputerModel, ComputerManufacturer, Architecture, ProcessorName, ProcessorCores,
             TotalMemoryGB, AvailableMemoryGB, MemoryUsagePercent, CreatedAt)
            VALUES
            (@MachineId, @ComputerName, @ComputerModel, @ComputerManufacturer, @Architecture, @ProcessorName, @ProcessorCores,
             @TotalMemoryGB, @AvailableMemoryGB, @MemoryUsagePercent, @CreatedAt)
            """;

        await connection.ExecuteAsync(
            insertQuery,
            new
            {
                MachineId = machineId,
                ComputerName = hardware.System.MachineName,
                ComputerModel = hardware.System.Platform,
                ComputerManufacturer = hardware.System.UserName,
                hardware.System.Architecture,
                hardware.Cpu.ProcessorName,
                ProcessorCores = hardware.Cpu.ProcessorCount,
                TotalMemoryGB = hardware.Memory.TotalPhysicalMemory,
                AvailableMemoryGB = hardware.Memory.AvailablePhysicalMemory,
                MemoryUsagePercent = hardware.Memory.MemoryUsagePercentage,
                CreatedAt = DateTime.UtcNow
            }).ConfigureAwait(false);
    }

